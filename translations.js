/* ══════════════════════════════════════════
   Language cycling: AR → EN → FR → AR …
   ══════════════════════════════════════════ */
const langOrder = ['ar', 'en', 'fr'];
let currentLangIndex = 0; // starts at Arabic

function toggleLang() {
  currentLangIndex = (currentLangIndex + 1) % langOrder.length;
  applyLang(langOrder[currentLangIndex]);
}

function applyLang(lang) {
  const t = translations[lang];
  document.documentElement.dir  = t.dir;
  document.documentElement.lang = t.lang;

  /* Update the button label to show the NEXT language */
  const nextLang = langOrder[(langOrder.indexOf(lang) + 1) % langOrder.length];
  document.getElementById('langBtn').textContent = nextLang.toUpperCase();

  for (const [id, val] of Object.entries(t)) {
    if (['dir', 'lang', 'langBtn'].includes(id)) continue;
    const el = document.getElementById(id);
    if (!el) continue;
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else if (el.tagName === 'OPTION') {
      el.textContent = val;
    } else {
      el.innerHTML = val;
    }
  }
}